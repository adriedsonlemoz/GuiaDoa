import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function validateApiUrl(value) {
  const url = new URL(String(value || '').trim());
  const host = url.hostname.toLowerCase().replace(/\.$/, '');
  if (url.protocol !== 'https:' || url.username || url.password ||
      host === 'localhost' || host.endsWith('.localhost') || host === '0.0.0.0' ||
      host.startsWith('127.') || host === '[::1]' || host === '[::]' ||
      /^\[::ffff:(?:7f[0-9a-f]{2}:|0:0\])/.test(host) || url.search || url.hash) {
    throw new Error('VITE_API_URL must use HTTPS without credentials, query, fragment or loopback hosts.');
  }
  return url.href.replace(/\/$/, '');
}

export function readAndroidVersion(root) {
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const { versionCode } = JSON.parse(readFileSync(join(root, 'mobile/android-version.json'), 'utf8'));
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error('Invalid application version.');
  }
  if (!Number.isInteger(versionCode) || versionCode < 1 || versionCode > 2100000000) {
    throw new Error('Android versionCode must be an integer between 1 and 2100000000.');
  }
  return { version, versionCode };
}

export function applyAndroidVersion(root) {
  const { version, versionCode } = readAndroidVersion(root);
  const appDir = join(root, 'android/app');
  const buildFile = join(appDir, 'build.gradle');
  const source = readFileSync(buildFile, 'utf8');
  const marker = "apply from: 'guiadoa-version.gradle'";
  writeFileSync(join(appDir, 'guiadoa-version.gradle'),
    `// Generated by scripts/android-build-config.mjs.\nandroid {\n    defaultConfig {\n        versionCode ${versionCode}\n        versionName "${version}"\n    }\n}\n`);
  if (!source.includes(marker)) appendFileSync(buildFile, `\n${marker}\n`);
  return { version, versionCode };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const mode = process.argv[2];
  const root = process.cwd();
  if (mode === 'validate') {
    validateApiUrl(process.env.VITE_API_URL);
    const config = JSON.parse(readFileSync(join(root, 'capacitor.config.json'), 'utf8'));
    if (config.server?.url || config.server?.cleartext || config.server?.androidScheme !== 'https') {
      throw new Error('APK must load bundled assets over the local HTTPS scheme.');
    }
    const { version, versionCode } = readAndroidVersion(root);
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `version=${version}\nversion_code=${versionCode}\n`);
    console.log(`Android: ${version} (${versionCode})`);
  } else if (mode === 'apply') {
    console.log(applyAndroidVersion(root));
  } else {
    throw new Error('Usage: node scripts/android-build-config.mjs validate|apply');
  }
}
